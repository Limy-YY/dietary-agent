-- 3. 前置校验：目标菜必须都在库里，避免对着错误基线写残数据
DO $$
DECLARE v_n integer; v_miss text;
BEGIN
  IF to_regclass('core.dish') IS NULL THEN
    RAISE EXCEPTION 'core.dish 未建：先还原 01 备份并跑完既有迁移链，再跑本脚本';
  END IF;
  SELECT count(*) INTO v_n FROM _dish_steps;
  IF v_n <> 222 THEN
    RAISE EXCEPTION '步骤数据应为 222 道，实为 % 道', v_n;
  END IF;
  SELECT string_agg(s.dish_id, ', ' ORDER BY s.dish_id) INTO v_miss
  FROM _dish_steps s LEFT JOIN core.dish d ON d.dish_id = s.dish_id
  WHERE d.dish_id IS NULL OR d.is_deleted;
  IF v_miss IS NOT NULL THEN
    RAISE EXCEPTION '以下目标菜不在 core.dish 或已停用：%', v_miss;
  END IF;
END $$;

-- 4. 字段就位
ALTER TABLE core.dish ADD COLUMN IF NOT EXISTS steps text[];
COMMENT ON COLUMN core.dish.steps IS
 '做法步骤（有序 text[]，2~3 条：做法 + 火候/时间 + 关键调味）；前端 dishes[].steps 按序渲染，tip 仍取 method_text；-LS 与基础菜同步骤、盐量按减半口径';

-- 5. 写步骤（幂等：仅内容变化才更新，顺带 touch updated_at 使菜品指纹失效）
UPDATE core.dish AS d
SET steps = v.steps,
    updated_at = now()
FROM _dish_steps AS v
WHERE d.dish_id = v.dish_id
  AND d.steps IS DISTINCT FROM v.steps;

-- 6. 兜底：未覆盖的菜（后续新增）若 source_row 带数组型 steps，先按原样迁入，避免前端拿到空步骤
UPDATE core.dish d
SET steps = sub.arr,
    updated_at = now()
FROM (
  SELECT x.dish_id,
         array_agg(t.step_text ORDER BY t.ord) AS arr
  FROM core.dish x
  CROSS JOIN LATERAL jsonb_array_elements_text(x.source_row -> 'steps') WITH ORDINALITY AS t(step_text, ord)
  WHERE x.steps IS NULL
    AND NOT x.is_deleted
    AND jsonb_typeof(x.source_row -> 'steps') = 'array'
  GROUP BY x.dish_id
) sub
WHERE d.dish_id = sub.dish_id
  AND d.steps IS NULL;

-- 7. method_text 归一：DISH-179 的说明性文字收进 steps，做法名只留「开袋即食」
UPDATE core.dish
SET method_text = '开袋即食',
    updated_at = now()
WHERE dish_id = 'DISH-179'
  AND method_text <> '开袋即食';

-- 8. 落库断言：覆盖、条数、-LS 一致性、即食标注、method_text 纯做法名
DO $$
DECLARE
  v_n integer; v_gap integer; v_bad integer; v_ls integer; v_imm integer; v_mt integer;
  v_cov integer; v_total integer;
BEGIN
  SELECT count(*) INTO v_total FROM core.dish WHERE NOT is_deleted;
  SELECT count(*) INTO v_cov FROM core.dish WHERE NOT is_deleted AND steps IS NOT NULL AND cardinality(steps) > 0;
  IF v_cov <> v_total THEN
    RAISE EXCEPTION '仍有 % 道菜无 steps（共 % 道有步骤 / % 道在库）', v_total - v_cov, v_cov, v_total;
  END IF;

  SELECT count(*) INTO v_gap
  FROM _dish_steps s JOIN core.dish d USING (dish_id)
  WHERE d.steps IS NULL OR cardinality(d.steps) NOT BETWEEN 2 AND 3;
  IF v_gap <> 0 THEN
    RAISE EXCEPTION '本次 222 道中 % 道步骤条数不在 2~3 条或为空', v_gap;
  END IF;

  SELECT count(*) INTO v_ls
  FROM core.dish d
  JOIN core.dish b ON b.dish_id = replace(d.dish_id, '-LS', '')
  WHERE d.dish_id LIKE '%-LS' AND NOT d.is_deleted
    AND d.steps::text <> replace(b.steps::text,
        '精盐 ' || trim_scale(b.default_salt_g)::text || 'g',
        '精盐 ' || trim_scale(d.default_salt_g)::text || 'g');
  IF v_ls <> 0 THEN
    RAISE EXCEPTION '有 % 道 -LS 变体的步骤与基础菜不一致（应只差精盐克数）', v_ls;
  END IF;

  SELECT count(*) INTO v_imm
  FROM core.dish d
  WHERE d.dish_id IN ('DISH-122', 'DISH-123', 'DISH-129', 'DISH-130', 'DISH-131', 'DISH-132', 'DISH-133', 'DISH-134', 'DISH-135', 'DISH-136', 'DISH-137', 'DISH-138', 'DISH-179')
    AND NOT EXISTS (
      SELECT 1 FROM unnest(d.steps) s
      WHERE s LIKE '%直接食用%' OR s LIKE '%按包装即食%' OR s LIKE '%直接饮用%' OR s LIKE '%煮透后饮用%'
    );
  IF v_imm <> 0 THEN
    RAISE EXCEPTION '有 % 道即食/水果类菜缺「直接食用 / 按包装即食」标注', v_imm;
  END IF;

  SELECT count(*) INTO v_mt
  FROM core.dish
  WHERE NOT is_deleted AND (method_text LIKE '%。%' OR length(method_text) > 30);
  IF v_mt <> 0 THEN
    RAISE EXCEPTION '有 % 道菜的 method_text 仍含分步说明或过长，应只留做法名', v_mt;
  END IF;

  SELECT count(*) INTO v_n FROM core.dish WHERE NOT is_deleted AND steps IS NOT NULL;
  RAISE NOTICE 'steps 补录完成：库内 % 道菜全部有步骤；本次 222 道均 2~3 条；-LS 与基础菜一致；即食类已统一标注。', v_n;
END $$;

COMMIT;

